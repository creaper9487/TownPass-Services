from app.tools.crawlers.schemas import Notice


def fetch_notices() -> list[Notice]:
    """【爬什麼】輔具中心官網「最新消息」裡目前有效的公告（休館、服務異動、系統維護）。

    用途：後端每 N 分鐘（PUSH_CHECK_MINUTES）呼叫一次，發現「新的」公告 id 就推播 service.notice
    給所有使用者，推播內容就是 title。之後也會給 GET /notices 用。

    ─────────────────────────────────────────
    網址
        https://tpap.gov.taipei/app37/newsView/index（最新消息列表，有分頁 /newsView/query）
        每則公告：https://tpap.gov.taipei/app37/newsView/detail?newsid=...
        _calendar_source.py 的 _fetch_closures() 已經在爬這兩頁，可以共用 HTML 解析與快取。

    ─────────────────────────────────────────
    步驟
        1. 讀最新消息列表（含分頁，最多 20 頁），拿到每則公告的 newsid、標題、發布日期。
        2. 只要「跟輔具借用 / 中心服務有關」的公告：休館、服務異動、系統維護、取貨相關。
           其他（活動、研習、徵才）不要回傳，不然會推播一堆不相關的通知。
        3. 點進每則公告拿內文；判斷適用哪些中心、生效 / 結束時間。
        4. 已經結束（ends_at 早於現在）的公告不要回傳。

    ─────────────────────────────────────────
    網頁上看到的 → 要填的欄位
        | 網頁上的東西                              | 欄位          | 範例                                   |
        |-------------------------------------------|---------------|----------------------------------------|
        | 網址裡的 newsid                           | id            | "252"                                  |
        | 公告標題                                  | title         | "國慶連假休館公告"                     |
        | 公告內文（純文字）                        | body          | "合宜、西區輔具中心 10/9～10/12 休館…" |
        | 內文提到的中心（合宜/南區/西區），全部適用給 [] | center_ids | ["heyi", "west"]                       |
        | 休館 / 異動開始時間（沒有給 None）         | starts_at     | "2026-10-09T00:00:00+08:00"            |
        | 休館 / 異動結束時間（沒有給 None）         | ends_at       | "2026-10-12T23:59:59+08:00"            |
        | 發布日期                                  | published_at  | "2026-09-29T00:00:00+08:00"            |

    ─────────────────────────────────────────
    注意
        - id 一定要用官網的 newsid，每次爬都一樣；後端靠 id 判斷「新公告」，id 變了就會重複推播。
        - title 會直接出現在使用者手機的鎖定畫面，不可含個資。
        - 時間一律帶 +08:00。
        - 抓失敗直接 raise，後端下次再試；不要回 []（回 [] 不會推播，但會讓 GET /notices 變空）。

    ─────────────────────────────────────────
    回傳範例
        [
            {
                "id": "252",
                "title": "國慶連假休館公告",
                "body": "合宜、西區輔具中心 115/10/9～10/12 休館，10/13 恢復服務。",
                "center_ids": ["heyi", "west"],
                "starts_at": "2026-10-09T00:00:00+08:00",
                "ends_at": "2026-10-12T23:59:59+08:00",
                "published_at": "2026-09-29T00:00:00+08:00"
            }
        ]

    檢查：python -m app.tools.crawlers.check notices
    """
    raise NotImplementedError("fetch_notices 尚未實作")
